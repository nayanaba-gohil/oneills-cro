"""Generates section 2a "Shop tyres by vehicle make" (A to Z letter bar + one panel per letter) and splices it
into src/home-content.html between the 2a and 2b markers. Run from the homepage folder:
    python3 tools/makes_section.py
Edit data/vehicle-makes.json to add or change makes. Logos are the cdn.wheel-size.com files the live /tyres/vehicles page uses.
"""
import html, json, pathlib, string

# data/vehicle-makes.json: [{name, slug, logo}], the 81 makes on the live /tyres/vehicles page (client supplied, Oct 2026).
# slug is taken from the wheel-size logo file name (e.g. great-wall, mercedes, kg-mobility), which is what the live
# /tyres/vehicles/{slug} URLs use for the makes checked so far. Order doesn't matter: the script sorts A to Z.
ROOT = pathlib.Path(__file__).resolve().parent.parent
MAKES = [(m['name'], m['slug'], m['logo']) for m in json.loads((ROOT / 'data' / 'vehicle-makes.json').read_text())]
TOTAL_MAKES = len(MAKES)  # shown on the "All N makes" link

e = lambda s: html.escape(s, quote=True)
LETTERS = string.ascii_uppercase
groups = {L: sorted([m for m in MAKES if m[0][0].upper() == L], key=lambda m: m[0].lower()) for L in LETTERS}
available = [L for L in LETTERS if groups[L]]
default = 'A' if groups['A'] else available[0]

# Desktop shows up to 10 makes per row, so every letter (the biggest group is M, with 9) fits on one row, and the
# panel reserves one row of two-line tiles: switching letters never moves the page. Phones and tablets wrap to 3 or 6
# per row and grow with the group (the bar stays put, only content below it moves).
assert max(len(g) for g in groups.values()) <= 10, 'a letter has more than 10 makes: raise lg:grid-cols or the reserved height'
min_h = 'lg:min-h-[7.75rem]'

PILL = 'inline-flex items-center rounded-full border border-brand-200 bg-brand-50 px-3.5 py-1.5 text-sm font-semibold text-brand-700 hover:border-brand-400 hover:bg-brand-100'
ARROW = 'flex h-10 w-10 shrink-0 items-center justify-center rounded-xl text-navy-900 hover:bg-slate-100 disabled:cursor-not-allowed disabled:text-slate-300 disabled:hover:bg-transparent'

def tab(L):
    if not groups[L]:
        return (f'<button type="button" role="tab" aria-disabled="true" disabled '
                f'class="h-10 min-w-[2.5rem] shrink-0 cursor-not-allowed rounded-xl px-1 text-[15px] text-slate-300">{L}</button>')
    lo = L.lower()
    return (f'<button type="button" role="tab" id="mk-tab-{lo}" data-letter="{L}" aria-controls="mk-panel-{lo}" '
            f':aria-selected="selected.{L}" :tabindex="tabIndex.{L}" :class="letterCls.{L}" @click="pick" '
            f'class="h-10 min-w-[2.5rem] shrink-0 rounded-xl px-1 text-[15px]"><span class="sr-only">Makes starting with </span>{L}</button>')

def tile(name, slug, logo):
    return (f'<li><a href="/tyres/vehicles/{slug}" class="flex h-full flex-col items-center justify-center gap-2 rounded-xl border border-slate-200 bg-white px-2 py-3 text-center hover:border-brand-500">'
            f'<img src="{logo}" alt="{e(name)} logo" width="64" height="64" loading="lazy" class="h-10 w-10 object-contain sm:h-12 sm:w-12">'
            f'<span class="text-xs font-semibold text-navy-900 sm:text-sm">{e(name)}<span class="sr-only"> tyres</span></span></a></li>')

def panel(L):
    lo = L.lower()
    cloak = '' if L == default else ' x-cloak'
    tiles = '\n          '.join(tile(*m) for m in groups[L])
    return f'''        <div role="tabpanel" id="mk-panel-{lo}" aria-labelledby="mk-tab-{lo}" x-show="shown.{L}"{cloak}>
          <ul class="grid grid-cols-3 gap-2 sm:grid-cols-6 sm:gap-3 lg:grid-cols-10">
          {tiles}
          </ul>
        </div>'''

section = f'''  <!-- ========== 2a. Shop tyres by vehicle make ========== -->
  <!-- Generated by tools/makes_section.py. A to Z letter bar (ohMakes): pick a letter to see the makes that start with it.
       Every make link is in the HTML for search engines; Alpine shows one letter at a time. Letters with no makes are disabled. -->
  <section id="makes" class="bg-slate-50 py-12 lg:py-16" aria-labelledby="makes-title" x-data="ohMakes" data-letters="{''.join(available)}" data-default="{default}">
    <div class="mx-auto max-w-7xl px-4 lg:px-6">
      <div class="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
        <div class="min-w-0 flex-1">
          <h2 id="makes-title" class="font-display text-2xl font-bold tracking-tight text-navy-900 sm:text-3xl">Shop tyres by vehicle make</h2>
          <p class="mt-2 text-slate-600">Pick the first letter of your make, then choose it to see tyres that fit your car, ute or 4WD.</p>
        </div>
        <a href="/tyres/vehicles" class="{PILL} shrink-0 self-start sm:self-auto">All {TOTAL_MAKES} makes</a>
      </div>

      <!-- A to Z bar: arrows step to the previous or next letter that has makes; the strip scrolls sideways below 1024px -->
      <div class="mt-8 flex items-center gap-1 rounded-2xl bg-white p-1.5 ring-1 ring-slate-200">
        <button type="button" @click="prev" :disabled="atStart" class="{ARROW}"><span class="sr-only">Previous letter</span><svg class="h-5 w-5 rotate-90" aria-hidden="true"><use href="#i-chevron-down"></use></svg></button>
        <div class="relative min-w-0 flex-1 overflow-x-auto [scrollbar-width:none] [&::-webkit-scrollbar]:hidden" x-ref="strip">
          <div role="tablist" aria-label="Vehicle makes A to Z" class="flex min-w-max justify-between gap-1" @keydown.arrow-left.prevent="prevKey" @keydown.arrow-right.prevent="nextKey">
            {chr(10).join('            ' + tab(L) for L in LETTERS).lstrip()}
          </div>
        </div>
        <button type="button" @click="next" :disabled="atEnd" class="{ARROW}"><span class="sr-only">Next letter</span><svg class="h-5 w-5 -rotate-90" aria-hidden="true"><use href="#i-chevron-down"></use></svg></button>
      </div>

      <div class="mt-6 {min_h}">
{chr(10).join(panel(L) for L in available)}
      </div>
    </div>
  </section>

'''

p = pathlib.Path('src/home-content.html'); t = p.read_text()
a = t.index('  <!-- ========== 2a. Shop tyres by vehicle make ========== -->')
b = t.index('  <!-- ========== 2b. 4WD, truck, fleet and farm (in-store services) ========== -->')
p.write_text(t[:a] + section + t[b:])
print(f'section 2a: {len(MAKES)} makes, letters {"".join(available)}, default {default}, biggest group {max(len(g) for g in groups.values())}')
